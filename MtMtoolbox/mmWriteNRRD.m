function mmWriteNRRD(filename, mv, options)
%MMWRITENRRD  Save a medicalVolume as a NRRD file that 3D Slicer can open
% MATLAB can read NRRD files with medicalVolume, but it can't write them.
% This function writes a medicalVolume as a .nrrd file (an image volume),
% or as a .seg.nrrd file (a Slicer segmentation, with named and colored
% segments), with the same voxel spacing, orientation, and position.
%
% Usage:
%   mmWriteNRRD(filename, mv)
%   mmWriteNRRD(filename, labelMV, Segments=segT)
%
% INPUTS
%   filename: the file to write (.nrrd, or .seg.nrrd for a segmentation)
%   mv:       a medicalVolume. For a segmentation, its voxels hold the
%             label value of each voxel (0 = background). A segmentation
%             with layers (4-D voxels) is saved with its layers: Segments
%             is then required, with its Layer column
%
%   Name-Value options
%   - Segments: a table with the variables SegName, LabelValue, and Color
%               (like the output of mmGetSlicerSegmentInfo). Writes the
%               segment names and colors, so that Slicer opens the file as
%               a segmentation. Labels that are not in the volume are skipped
%   - Compress: false writes the voxels uncompressed. Default true (gzip)
%
% EXAMPLES
%   mmWriteNRRD("MRBT1stripped.nrrd", strippedMV)
%   segT = table("brain", 1, [0.9 0.7 0.6], VariableNames=["SegName" "LabelValue" "Color"]);
%   mmWriteNRRD("brain.seg.nrrd", brainMV, Segments=segT)
%
% See also medicalVolume, mmGetSlicerSegmentInfo

% ---
% AUTHOR: Ernesto Salcedo, PhD
% SITE: University of Colorado Modern Human Anatomy
% UPDATED: 11/10/2026

arguments
    filename (1,1) string
    mv medicalVolume
    options.Segments table = table.empty
    options.Compress (1,1) logical = true
end

V = mv.Voxels;
segT = options.Segments;
numLayers = size(V, 4);
if ndims(V) > 4 || (ndims(V) == 4 && ~all(ismember(["SegName" "LabelValue" "Color" "Layer"], segT.Properties.VariableNames)))
    error("mmWriteNRRD:notVolume", "The medicalVolume must hold a single 3-D volume, " + ...
        "or a segmentation with layers (4-D) together with its segment table (Segments=segT, with a Layer column).")
end
if numLayers > 1 && max(segT.Layer) > numLayers
    error("mmWriteNRRD:layers", "The segment table has %d layers, but the volume has %d.", max(segT.Layer), numLayers)
end
types = dictionary(["logical" "uint8" "int8" "uint16" "int16" "uint32" "int32" "single" "double"], ...
    ["unsigned char" "unsigned char" "signed char" "unsigned short" "short" "unsigned int" "int" "float" "double"]);
if ~isKey(types, class(V))
    error("mmWriteNRRD:type", "Voxels of class %s can't be saved.", class(V))
end
if islogical(V)
    V = uint8(V);
end

% position and axes of the voxel grid, in LPS (the coordinates of NRRD files)
R = mv.VolumeGeometry;
[x, y, z] = intrinsicToWorld(R, [1 2 1 1], [1 1 2 1], [1 1 1 2]);
P = [x(:) y(:) z(:)];
if R.PatientCoordinateSystem == "RAS+" % a volume read from a NIfTI file
    P(:, 1:2) = -P(:, 1:2); % RAS -> LPS
end
origin = P(1,:);
axes = P(2:4,:) - origin; % row k: the step along array dimension k

fid = fopen(filename, "w");
if fid == -1
    error("mmWriteNRRD:cannotWrite", "Cannot write the file: %s", filename)
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "NRRD0004\n");
fprintf(fid, "type: %s\n", types(class(V)));
if numLayers == 1
    fprintf(fid, "dimension: 3\n");
    fprintf(fid, "space: left-posterior-superior\n");
    fprintf(fid, "sizes: %d %d %d\n", size(V, 1:3));
    fprintf(fid, "space directions: (%.10g,%.10g,%.10g) (%.10g,%.10g,%.10g) (%.10g,%.10g,%.10g)\n", axes');
    fprintf(fid, "kinds: domain domain domain\n");
else % a segmentation with layers: in the file, the layers are the first dimension
    fprintf(fid, "dimension: 4\n");
    fprintf(fid, "space: left-posterior-superior\n");
    fprintf(fid, "sizes: %d %d %d %d\n", numLayers, size(V, 1:3));
    fprintf(fid, "space directions: none (%.10g,%.10g,%.10g) (%.10g,%.10g,%.10g) (%.10g,%.10g,%.10g)\n", axes');
    fprintf(fid, "kinds: list domain domain domain\n");
end
fprintf(fid, "endian: little\n");
if options.Compress
    fprintf(fid, "encoding: gzip\n");
else
    fprintf(fid, "encoding: raw\n");
end
fprintf(fid, "space origin: (%.10g,%.10g,%.10g)\n", origin);

% segment names and colors, as Slicer writes them
if ~isempty(segT)
    hasLayers = numLayers > 1;
    fprintf(fid, "Segmentation_ContainedRepresentationNames:=Binary labelmap|\n");
    fprintf(fid, "Segmentation_MasterRepresentation:=Binary labelmap\n");
    n = 0;
    for s = 1:height(segT)
        value = segT.LabelValue(s);
        layer = 1;
        if hasLayers
            layer = segT.Layer(s);
        end
        voxels = find(V(:, :, :, layer) == value);
        if isempty(voxels) || value == 0
            continue
        end
        [i, j, k] = ind2sub(size(V, 1:3), voxels);
        fprintf(fid, "Segment%d_Color:=%.6g %.6g %.6g\n", n, segT.Color(s, :));
        fprintf(fid, "Segment%d_ColorAutoGenerated:=0\n", n);
        fprintf(fid, "Segment%d_Extent:=%d %d %d %d %d %d\n", n, min(i)-1, max(i)-1, min(j)-1, max(j)-1, min(k)-1, max(k)-1);
        if hasLayers
            fprintf(fid, "Segment%d_ID:=Segment_%d\n", n, s); % label values can repeat across layers
        else
            fprintf(fid, "Segment%d_ID:=Segment_%d\n", n, value);
        end
        fprintf(fid, "Segment%d_LabelValue:=%d\n", n, value);
        fprintf(fid, "Segment%d_Layer:=%d\n", n, layer - 1);
        fprintf(fid, "Segment%d_Name:=%s\n", n, segT.SegName(s));
        fprintf(fid, "Segment%d_NameAutoGenerated:=0\n", n);
        n = n + 1;
    end
end
fprintf(fid, "\n"); % a blank line ends the header

if numLayers > 1
    V = permute(V, [4 1 2 3]);
end
bytes = typecast(V(:), "uint8"); % little-endian on all the computers that MATLAB runs on
if options.Compress
    bytes = gzipBytes(bytes);
end
fwrite(fid, bytes, "uint8");
end


function out = gzipBytes(bytes)
% Compress bytes with gzip, using Java
byteStream = java.io.ByteArrayOutputStream();
zipStream = java.util.zip.GZIPOutputStream(byteStream);
zipStream.write(typecast(bytes, "int8"), 0, numel(bytes)); % Java bytes are signed
zipStream.close();
out = typecast(byteStream.toByteArray(), "uint8");
end
